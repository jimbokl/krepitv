export function boundedSceneStep(index, count) {
  if (!Number.isInteger(count) || count < 1) return 0;
  return Math.max(0, Math.min(count - 1, Number.isFinite(index) ? Math.trunc(index) : 0));
}

export function scenePlaybackNext(index, count) {
  const step = boundedSceneStep(index, count);
  return { step: boundedSceneStep(step + 1, count), playing: step + 1 < count - 1 };
}
